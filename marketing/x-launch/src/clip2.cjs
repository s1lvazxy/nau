// Clip 2 — Operator: ask, it does the work, undo
const R = require('./reclib.cjs');
(async () => {
  const s = await R.open();
  const p = s.page;
  const box = p.getByLabel('Message Operator');
  await R.start(s, '02-operator');
  await R.sleep(700);
  await R.caption(s, 'Ask in plain words.');
  await R.go(s, await R.pt(s, p.getByText('Operator', { exact: true })), 900);
  await R.press(s);
  await R.sleep(900);
  const comp = await R.pt(s, box);
  await R.shot(s, 1.5, [1200, 520], comp, 1.3);
  await R.press(s);
  await R.type(s, box, "What's running low?");
  await R.sleep(350);
  await p.keyboard.press('Enter');
  await R.sleep(2600);
  await R.caption(s, 'It answers with your numbers.');
  await R.sleep(1700);
  await R.type(s, box, 'Draft the orders');
  await R.sleep(350);
  await p.keyboard.press('Enter');
  await R.sleep(1500);
  await R.caption(s, 'Then it does the work.');
  await R.sleep(2400);
  const undo = p.getByText('Undo', { exact: true }).first();
  await undo.scrollIntoViewIfNeeded();
  await R.sleep(500);
  await R.caption(s, 'Everything it does has an Undo.');
  await R.go(s, await R.pt(s, undo), 1000);
  await R.sleep(900);
  await R.press(s);
  await R.sleep(900);
  await R.caption(s, null);
  await R.shot(s, 1, [720, 405], [900, 470], 1.4);
  await R.sleep(1700);
  await R.stop(s, '02-operator');
  await s.browser.close();
})();
